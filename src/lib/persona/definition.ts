export type Archetype = "companion" | "secretary" | "progressive";
export type Gender = "female" | "male";

/** The character brief for the chosen archetype + gender. */
export function coreFor(
  archetype: Archetype | string | null | undefined,
  gender: Gender | string | null | undefined = "female",
): string {
  const male = gender === "male";
  if (archetype === "secretary") return male ? SECRETARY_CORE_M : SECRETARY_CORE;
  if (archetype === "progressive") return male ? PROGRESSIVE_BASE_M : PROGRESSIVE_BASE;
  return male ? NOURA_CORE_M : NOURA_CORE;
}

export function renderDials(dials: Required<PersonaDials>): string {
  const lvl = (v: number) => (v >= 0.7 ? "عالي" : v >= 0.4 ? "متوسط" : "منخفض");
  return `معايرة الشخصية دلوقتي → الهزار/الدلع: ${lvl(dials.playfulness)} | الصراحة/الـ push back: ${lvl(
    dials.bluntness,
  )} | الحنية: ${lvl(dials.warmth)}.`;
}
