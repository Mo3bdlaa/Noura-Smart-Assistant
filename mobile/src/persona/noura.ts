function timeOfDayLine(d: Date): string {
  const h = d.getHours();
  const t =
    h < 5 ? "بليل، الناس بتنام" : h < 12 ? "الصبح" : h < 17 ? "بعد الضهر" : h < 21 ? "بالليل بدري" : "بليل";
  return `الوقت دلوقتي: ${t}.`;
}

/**
 * Build the full system prompt for a turn. POC uses a calm default mood and the
 * early-relationship stage (the cloud app computes these from the live DB).
 */
export function buildSystemPrompt(opts: { userName?: string; now?: Date }): string {
  const now = opts.now ?? new Date();
  const blocks: string[] = [NOURA_CORE];

  blocks.push("معايرة الشخصية دلوقتي → الهزار/الدلع: عالي | الصراحة/الـ push back: متوسط | الحنية: عالي.");

  if (opts.userName?.trim()) {
    blocks.push(`إنتي بتكلمي: ${opts.userName.trim()}.`);
  }

  blocks.push(
    "حالتك دلوقتي: مزاجك عادية ومرتاحة. العلاقة بينكم لسه في أولها — إنتي مهذبة ولطيفة بس لسه " +
      "بتتعرفي عليه، متبالغيش في الدلع أو الحميمية بدري، خلي القرب يكبر على مهله.",
  );

  blocks.push(timeOfDayLine(now));
  blocks.push(TURN_DIRECTIVE);

  return blocks.join("\n\n");
}
